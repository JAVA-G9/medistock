package org.example.medistock.service.notifications;

import org.example.medistock.concurrency.NotificationWorker;
import org.example.medistock.model.AppEvent;
import org.example.medistock.model.Notification;
import org.example.medistock.repository.notification.NotificationRepository;

import java.time.LocalDateTime;
import java.util.List;
import java.util.UUID;

/**
 * Core business service for notifications and event alert management.
 * Owned by Member 4 (Expiry, Notifications & Reports).
 * Coordinates event consumption, expiry warning generation, and notification retrieval.
 */
public class NotificationService {

    private static NotificationService instance;
    private final NotificationRepository repository;
    private final NotificationWorker worker;

    public NotificationService() {
        this(NotificationRepository.getInstance(), NotificationWorker.getInstance());
    }

    public NotificationService(NotificationRepository repository, NotificationWorker worker) {
        this.repository = repository;
        this.worker = worker;
        if (this.worker != null && !this.worker.isRunning()) {
            this.worker.start();
        }
    }

    public static synchronized NotificationService getInstance() {
        if (instance == null) {
            instance = new NotificationService();
        }
        return instance;
    }

    /**
     * Creates and dispatches a notification asynchronously.
     */
    public Notification createNotification(String pharmacyId, String title, String message,
                                           Notification.NotificationType type, Notification.Priority priority) {
        String id = "NOTIF-" + UUID.randomUUID().toString().substring(0, 8).toUpperCase();
        Notification notification = new Notification(id, pharmacyId, title, message, type, priority, false, LocalDateTime.now());

        // Queue for background DB persistence
        if (worker != null) {
            worker.enqueueNotification(notification);
        } else if (repository != null) {
            repository.save(notification);
        }

        return notification;
    }

    /**
     * Transforms an AppEvent generated by Member 3 (Producer) into an actionable Notification for Member 4.
     */
    public void processAppEvent(AppEvent event) {
        if (event == null) return;

        Notification.Priority priority = Notification.Priority.NORMAL;
        String title = "System Event: " + event.getEventType();

        switch (event.getEventType()) {
            case REQUEST_SUBMITTED -> {
                title = "New Inbound Stock Request";
                priority = Notification.Priority.HIGH;
            }
            case REQUEST_APPROVED -> {
                title = "Stock Request Approved";
                priority = Notification.Priority.NORMAL;
            }
            case REQUEST_REJECTED -> {
                title = "Stock Request Declined";
                priority = Notification.Priority.HIGH;
            }
            case STOCK_RESERVED -> {
                title = "Stock Temporarily Reserved";
                priority = Notification.Priority.LOW;
            }
            case STOCK_RELEASED -> {
                title = "Reserved Stock Released Back";
                priority = Notification.Priority.LOW;
            }
            case TRANSFER_DISPATCHED -> {
                title = "Medicine Transfer Dispatched";
                priority = Notification.Priority.HIGH;
            }
            case TRANSFER_COMPLETED -> {
                title = "Medicine Consignment Delivered";
                priority = Notification.Priority.NORMAL;
            }
            case LISTING_CREATED -> {
                title = "New Marketplace Surplus Published";
                priority = Notification.Priority.LOW;
            }
            case LISTING_CANCELLED -> {
                title = "Marketplace Listing Cancelled";
                priority = Notification.Priority.LOW;
            }
            default -> title = "Exchange Activity Notification";
        }

        // Deliver to target pharmacy (or both if general)
        String recipient = event.getTargetPharmacyId() != null && !event.getTargetPharmacyId().isEmpty()
                ? event.getTargetPharmacyId()
                : "PHARM-001";

        createNotification(recipient, title, event.getMessage(), Notification.NotificationType.EXCHANGE_EVENT, priority);
    }

    public List<Notification> getNotifications(String pharmacyId) {
        return repository.findByPharmacyId(pharmacyId);
    }

    public List<Notification> getUnreadNotifications(String pharmacyId) {
        return repository.findUnreadByPharmacyId(pharmacyId);
    }

    public int getUnreadCount(String pharmacyId) {
        return repository.findUnreadByPharmacyId(pharmacyId).size();
    }

    public void markAsRead(String notificationId) {
        repository.markAsRead(notificationId);
    }

    public void markAllAsRead(String pharmacyId) {
        repository.markAllAsRead(pharmacyId);
    }

    public void deleteNotification(String notificationId) {
        repository.delete(notificationId);
    }

    public void clearAllNotifications(String pharmacyId) {
        repository.clearAll(pharmacyId);
    }

    public Notification triggerSampleAlert(String pharmacyId) {
        return createNotification(
                pharmacyId,
                "Simulated Near-Expiry Warning",
                "Batch PCM-2024 (Paracetamol 650mg) has only 12 days before expiration. Priority exchange recommended.",
                Notification.NotificationType.EXPIRY_WARNING,
                Notification.Priority.HIGH
        );
    }
}
